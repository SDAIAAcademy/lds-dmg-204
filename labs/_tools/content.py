def level_of(impact: int, law_blocks: str, benefits: str) -> str:
    """The policy's rule: High to Top Secret, Medium to Secret, None to Public; Low goes through
    step 4 (a law blocks disclosure: Restricted) and step 5 (benefits outweigh harm: Public)."""
    if impact == 3:
        return "سري للغاية"
    if impact == 2:
        return "سري"
    if impact == 0:
        return "عام"
    if law_blocks == "نعم":
        return "مقيد"
    return "عام" if benefits == "نعم" else "مقيد"


